// Keep actual SQLite execution, but reproduce the missing module reported by
// the Samsung Android database when preparing a virtual-table join.
class AndroidModuleFactory implements DatabaseFactory {
  int rtreeAttempts = 0;
  final String failure;
  AndroidModuleFactory({this.failure = 'no such module: rtree'});
  @override
  Future<Database> openDatabase(String path, {OpenDatabaseOptions? options}) async =>
      AndroidModuleDatabase(await databaseFactoryFfi.openDatabase(path, options:options), this);
  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

class AndroidModuleDatabase implements Database {
  final Database delegate;
  final AndroidModuleFactory owner;
  AndroidModuleDatabase(this.delegate, this.owner);
  @override
  Future<List<Map<String, Object?>>> rawQuery(String sql, [List<Object?>? arguments]) {
    if (sql.contains('JOIN establishment_rtree')) {
      owner.rtreeAttempts++;
      throw StateError(owner.failure);
    }
    return delegate.rawQuery(sql, arguments);
  }
  @override
  Future<List<Map<String, Object?>>> query(String table, {
    bool? distinct, List<String>? columns, String? where, List<Object?>? whereArgs,
    String? groupBy, String? having, String? orderBy, int? limit, int? offset,
  }) => delegate.query(table, distinct:distinct, columns:columns, where:where,
    whereArgs:whereArgs, groupBy:groupBy, having:having, orderBy:orderBy, limit:limit, offset:offset);
  @override
  Future<void> close() => delegate.close();
  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

// Exercise the production install, metadata validation, RTree/category SQL and
// radius filtering against the shipped real extract, without an Android channel
// or a fake DatabaseFactory. The fixture remains explicitly incomplete.
void main() {
  late Map<String, dynamic> catalog;
  late DirectoryPack pack;
  late DirectoryCategories categories;
  late Directory support;
  late NativeDirectoryBackend backend;
  final assetDirectory = p.join('assets', 'directory_sample');
  const latitude = 48.865;
  const longitude = 2.333;

  setUpAll(() async {
    sqfliteFfiInit();
    catalog = jsonDecode(
      await File(p.join(assetDirectory, 'catalog.json')).readAsString(),
    ) as Map<String, dynamic>;
    pack = parseDirectoryCatalog(catalog).singleWhere((p) => p.id == 'fr-75');
    categories = DirectoryCategories(
      jsonDecode(
        await File(p.join('tools', 'national_directory', 'categories.json'))
            .readAsString(),
      ) as Map<String, dynamic>,
    );
  });

  setUp(() async {
    support = await Directory.systemTemp.createTemp(
      'prospecto-real-sqlite-test-',
    );
    backend = NativeDirectoryBackend(
      supportDirectory: () async => support,
      factory: databaseFactoryFfi,
    );
    await backend.install(
      pack,
      localFile: p.join(assetDirectory, p.basename(pack.url!.path)),
    );
  });

  tearDown(() async {
    // Only the directory generated by this test inside the OS temp root is
    // removed; all fixture assets and the production support directory remain.
    expect(p.isWithin(Directory.systemTemp.path, support.path), isTrue);
    await support.delete(recursive: true);
  });

  test('real Paris pack installs and returns distinct CHR and GMS businesses',
      () async {
    expect(catalog['is_demo'], isFalse);
    expect(parseDirectoryCatalog(catalog).every((p) => !p.demo && !p.complete),
        isTrue);
    expect(pack.demo, isFalse);
    expect(pack.complete, isFalse);
    final installed = (await backend.installed()).single;
    expect(installed.sqliteHash, pack.sqliteHash);
    expect(installed.demo, isFalse);
    expect(installed.complete, isFalse);

    final chrCategories = categories.resolve('CHR');
    final gmsCategories = categories.resolve('GMS');
    expect(chrCategories, ['chr']);
    expect(gmsCategories, ['gms']);
    final chr = await backend.query(
      installed,
      latitude,
      longitude,
      3000,
      chrCategories,
    );
    final gms = await backend.query(
      installed,
      latitude,
      longitude,
      3000,
      gmsCategories,
    );
    expect(chr, isNotEmpty);
    expect(gms, isNotEmpty);
    expect(
      chr
          .map((r) => r.place.id)
          .toSet()
          .intersection(gms.map((r) => r.place.id).toSet()),
      isEmpty,
    );

    final cafe = chr.singleWhere((r) => r.place.siret == '44533010300026');
    expect(cafe.place.name, 'CAFE SIRENE FRANCE');
    expect(cafe.place.address, "26 AVENUE DE L'OPERA 75001 PARIS");
    final supermarket =
        gms.singleWhere((r) => r.place.siret == '44028375206686');
    expect(supermarket.place.name, 'CARREFOUR MARKET');
    expect(supermarket.place.address, contains('75009 PARIS'));

    for (final record in [...chr, ...gms]) {
      expect(record.place.siret, matches(RegExp(r'^\d{14}$')));
      expect(record.place.id, 'siret_${record.place.siret}');
      expect(record.place.siret, record.establishment['siret']);
      expect(record.place.address, isNotEmpty);
      expect(record.place.source, 'annuaire_sirene');
      expect(record.place.source, record.establishment['source']);
      expect(record.place.nafCode, record.establishment['naf_code']);
      expect(record.pack.complete, isFalse);
      expect(record.pack.demo, isFalse);
    }
    for (final record in chr) {
      expect(
        ['55.10Z', '56.10A', '56.10B', '56.10C', '56.30Z'],
        contains(record.place.nafCode),
      );
      expect(record.place.category, contains('CHR / HORECA'));
    }
    for (final record in gms) {
      expect(['47.11D', '47.11F'], contains(record.place.nafCode));
      expect(record.place.category,
          contains('Grandes et moyennes surfaces alimentaires'));
    }
  });

  test('real SQL query excludes businesses outside the selected radius',
      () async {
    final chr = categories.resolve('CHR');
    final within500 = await backend.query(
      pack,
      latitude,
      longitude,
      500,
      chr,
    );
    // These three fixture establishments are about 244 m, 411 m and 479 m
    // away. The wider 3 km fixture also contains more distant restaurants.
    expect(
      within500.map((r) => r.place.siret),
      unorderedEquals(['44533010300026', '80770830000189', '80770830000205']),
    );
    expect(
      await backend.query(pack, latitude, longitude, 100, chr),
      isEmpty,
    );
    expect(
      await backend.query(
        pack,
        latitude,
        longitude,
        500,
        categories.resolve('GMS'),
      ),
      isEmpty,
    );
    expect(
      await backend.query(pack, 45.764, 4.8357, 3000, null),
      isEmpty,
    );
    expect(
      await backend.query(pack, latitude, longitude, 3000, ['not_a_category']),
      isEmpty,
    );
  });

  test('real incomplete extract stays partial when the online complement fails',
      () async {
    var fallbackCalls = 0;
    final service = DirectoryService(
      backend: backend,
      categories: () async => categories,
    );
    final result = await service.search(
      lat: latitude,
      lon: longitude,
      radius: 3000,
      query: 'CHR',
      fallback: () async {
        fallbackCalls++;
        throw const SocketException('Offline test');
      },
    );
    expect(fallbackCalls, 1);
    expect(result.places, isNotEmpty);
    expect(result.local, isTrue);
    expect(result.partial, isTrue);
    expect(result.networkUnavailable, isTrue);
    expect(result.notice, contains('résultats incomplets'));
    expect(result.notice, isNot(contains('DÉMONSTRATION')));
    expect(result.details.keys, containsAll(result.places.map((p) => p.id)));
    expect((await backend.installed()).single.complete, isFalse);
  });

  test('Android without RTree returns the same real rows through ordinary SQL', () async {
    final factory=AndroidModuleFactory();
    final compatible=NativeDirectoryBackend(supportDirectory:() async=>support, factory:factory);
    final expected=await backend.query(pack,latitude,longitude,500,categories.resolve('CHR'));
    final actual=await compatible.query(pack,latitude,longitude,500,categories.resolve('CHR'));
    expect(actual.map((r)=>r.place.siret),expected.map((r)=>r.place.siret));
    expect(actual,hasLength(3));
    expect(factory.rtreeAttempts,1);
    expect(await compatible.query(pack,latitude,longitude,500,categories.resolve('GMS')),isEmpty);
    expect(factory.rtreeAttempts,1);
  });

  test('unrelated SQLite failures cannot be disguised as a compatible empty query', () async {
    final factory=AndroidModuleFactory(failure:'no such column: invalid_column');
    final broken=NativeDirectoryBackend(supportDirectory:() async=>support,factory:factory);
    await expectLater(broken.query(pack,latitude,longitude,500,categories.resolve('CHR')),
      throwsA(isA<StateError>().having((e)=>e.toString(),'message',contains('invalid_column'))));
  });
}
