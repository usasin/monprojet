import 'dart:convert';
import 'dart:io';
import 'package:crypto/crypto.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:path/path.dart' as p;
import 'package:sqflite/sqflite.dart';
import 'package:ai_prospect_gps/directory/directory_models.dart';
import 'package:ai_prospect_gps/directory/directory_platform_io.dart';

// SQLite execution is intentionally injected. These tests exercise the actual
// filesystem/download-integrity/activation code without an Android channel.
// The Python importer independently opens and checks the real SQLite packs.
class ValidatedFactory implements DatabaseFactory {
  DirectoryPack? pack;
  int opens = 0;
  @override
  Future<Database> openDatabase(
    String path, {
    OpenDatabaseOptions? options,
  }) async {
    opens++;
    expect(options?.readOnly, isTrue);
    return MetadataDatabase(pack!);
  }

  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

class MetadataDatabase implements Database {
  final DirectoryPack pack;
  MetadataDatabase(this.pack);
  @override
  Future<void> close() async {}
  @override
  Future<List<Map<String, Object?>>> rawQuery(
    String sql, [
    List<Object?>? arguments,
  ]) async {
    if (sql == 'PRAGMA quick_check')
      return [
        {'quick_check': 'ok'},
      ];
    if (sql.startsWith('PRAGMA table_info'))
      return 'key value id siret siren name address postal_code commune_code department region lat lon naf_code naf_version employee_band enterprise_size active source source_date geo_quality establishment_id category_id label scope scope_id year consumption_kwh power_kw power_kva segment source_url status quality_note'
          .split(' ')
          .map((s) => <String, Object?>{'name': s})
          .toList();
    throw StateError('Unexpected SQL $sql');
  }

  @override
  Future<List<Map<String, Object?>>> query(
    String table, {
    bool? distinct,
    List<String>? columns,
    String? where,
    List<Object?>? whereArgs,
    String? groupBy,
    String? having,
    String? orderBy,
    int? limit,
    int? offset,
  }) async {
    expect(table, 'pack_metadata');
    return {
      'schema_version': '1',
      for (final k in [
        'pack_id',
        'version',
        'department',
        'data_date',
        'coverage_complete',
        'is_demo',
      ])
        k: '${pack.json[k]}',
      'coverage_geojson': jsonEncode(pack.geometry),
    }
        .entries
        .map((e) => <String, Object?>{'key': e.key, 'value': e.value})
        .toList();
  }

  @override
  dynamic noSuchMethod(Invocation invocation) => super.noSuchMethod(invocation);
}

void main() {
  late Directory support;
  late ValidatedFactory factory;
  late NativeDirectoryBackend backend;
  Future<({DirectoryPack pack, File file})> fixture(String version) async {
    final bytes = utf8.encode('SQLite fixture $version');
    final compressed = gzip.encode(bytes);
    final file = File(p.join(support.path, 'fixture-$version.gz'));
    await file.writeAsBytes(compressed);
    final pack = DirectoryPack({
      'pack_id': 'fr-75',
      'version': version,
      'department': '75',
      'data_date': '2026-10-28',
      'coverage_complete': true,
      'is_demo': true,
      'coverage_geojson': {
        'type': 'Polygon',
        'coordinates': [
          [
            [1, 47],
            [3, 47],
            [3, 49],
            [1, 49],
            [1, 47],
          ],
        ],
      },
      'gzip_sha256': sha256.convert(compressed).toString(),
      'sqlite_sha256': sha256.convert(bytes).toString(),
      'gzip_size_bytes': compressed.length,
      'sqlite_size_bytes': bytes.length,
    });
    return (pack: pack, file: file);
  }

  setUp(() async {
    support = await Directory.systemTemp.createTemp(
      'prospecto-directory-test-',
    );
    factory = ValidatedFactory();
    backend = NativeDirectoryBackend(
      supportDirectory: () async => support,
      factory: factory,
    );
  });
  tearDown(() async {
    // The path is generated by createTemp within the system temporary directory.
    expect(p.isWithin(Directory.systemTemp.path, support.path), isTrue);
    await support.delete(recursive: true);
  });
  test('failed gzip or SQLite checksum never activates a pack', () async {
    final v1 = await fixture('1');
    factory.pack = v1.pack;
    final bad = DirectoryPack({
      ...v1.pack.json,
      'gzip_sha256': List.filled(64, '0').join(),
    });
    await expectLater(
      backend.install(bad, localFile: v1.file.path),
      throwsA(isA<DirectoryException>()),
    );
    final badSqlite = DirectoryPack({
      ...v1.pack.json,
      'sqlite_sha256': List.filled(64, '0').join(),
    });
    await expectLater(
      backend.install(badSqlite, localFile: v1.file.path),
      throwsA(isA<DirectoryException>()),
    );
    expect(await backend.installed(), isEmpty);
    expect(factory.opens, 0);
    final private = Directory(
      p.join(support.path, 'prospecto_national_directory_v1'),
    );
    expect(
      await private
          .list()
          .where((f) => p.basename(f.path).startsWith('staging-'))
          .toList(),
      isEmpty,
    );
  });
  test(
    'failed update retains old pack; valid update and rollback survive new service',
    () async {
      final v1 = await fixture('1'), v2 = await fixture('2');
      factory.pack = v1.pack;
      await backend.install(v1.pack, localFile: v1.file.path);
      final bad = DirectoryPack({
        ...v2.pack.json,
        'gzip_sha256': List.filled(64, '0').join(),
      });
      await expectLater(
        backend.install(bad, localFile: v2.file.path),
        throwsA(isA<DirectoryException>()),
      );
      expect((await backend.installed()).single.version, '1');
      factory.pack = v2.pack;
      await backend.install(v2.pack, localFile: v2.file.path);
      final restarted = NativeDirectoryBackend(
        supportDirectory: () async => support,
        factory: factory,
      );
      expect((await restarted.installed()).single.version, '2');
      expect(await restarted.rollback('fr-75'), isTrue);
      expect((await restarted.installed()).single.version, '1');
      await restarted.remove('fr-75');
      expect(await restarted.installed(), isEmpty);
      final private = Directory(
        p.join(support.path, 'prospecto_national_directory_v1'),
      );
      expect(
        await private.list().where((f) => f.path.endsWith('.sqlite')).toList(),
        isEmpty,
      );
    },
  );
  test(
    'post-install file corruption throws before SQL and cannot look empty',
    () async {
      final v1 = await fixture('1');
      factory.pack = v1.pack;
      await backend.install(v1.pack, localFile: v1.file.path);
      final file = File(
        p.join(
          support.path,
          'prospecto_national_directory_v1',
          '${v1.pack.sqliteHash}.sqlite',
        ),
      );
      await file.writeAsString('corrupt');
      await expectLater(
        backend.query(v1.pack, 48, 2, 1000, null),
        throwsA(isA<DirectoryException>()),
      );
    },
  );
  test('declared expansion limit prevents gzip bomb activation', () async {
    final v1 = await fixture('1');
    final short = DirectoryPack({...v1.pack.json, 'sqlite_size_bytes': 1});
    await expectLater(
      backend.install(short, localFile: v1.file.path),
      throwsA(isA<DirectoryException>()),
    );
    expect(await backend.installed(), isEmpty);
    expect(factory.opens, 0);
  });
  test(
    'HTTP catalog and pack URLs are refused without a network request',
    () async {
      await expectLater(
        backend.fetchCatalog(Uri.parse('http://example.com/catalog.json')),
        throwsA(isA<DirectoryException>()),
      );
      final v1 = await fixture('1');
      final insecure = DirectoryPack({
        ...v1.pack.json,
        'url': 'http://example.com/pack.gz',
      });
      await expectLater(
        backend.install(insecure),
        throwsA(isA<DirectoryException>()),
      );
      expect(await backend.installed(), isEmpty);
    },
  );
}
